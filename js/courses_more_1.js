/* ---------- 生成器 ---------- */
function toQ(a){ return { q:a[0], opts:a[1], ans:a[2], explain:a[3]||'' }; }

function buildCourse(gradeId, gradeName, subject, ed, outline, examQ, examTime){
  const units = outline.map(u=>({
    id:u.id, title:u.t,
    lessons:[
      { id:u.id+'r', title:u.t, type:'reading', paras:u.note },
      { id:u.id+'q', title:u.t+'·随堂测验', type:'quiz', questions:u.q.map(toQ) }
    ]
  }));
  units.push({ id:'exam', title:gradeName+'·期末模拟考', lessons:[
    { id:'exam1', title:subject+'·期末模拟考', type:'exam', timeLimit:examTime, questions:examQ.map(toQ) }
  ]});
  return {
    meta:{
      grade:gradeName, subject, edition:ed, volume:'',
      book:NATIONAL_TEXTBOOK,
      desc: subject+'（'+ed+'）'+gradeName+'纵向课程：知识点 + 随堂测验 + 期末模拟考。点「正版教材」前往国家中小学智慧教育平台（含人教版/苏教版）免费阅读。'
    },
    units
  };
}

